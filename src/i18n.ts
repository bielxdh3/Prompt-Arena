export const PT_BR_MESSAGES = { ...PT_BR_MESSAGES_BASE, ...PT_BR_MESSAGES_EXTRA } as const;

export type TranslationKey = keyof typeof PT_BR_MESSAGES;

export function normalizeAppLocale(value: unknown): AppLocale {
  return value === "pt-BR" || value === "en" ? value : "en";
}

export function loadAppLocale(storage: Pick<Storage, "getItem"> | null = typeof window === "undefined" ? null : window.localStorage): AppLocale {
  try {
    return normalizeAppLocale(storage?.getItem(APP_LOCALE_STORAGE_KEY));
  } catch {
    return "en";
  }
}

export function saveAppLocale(locale: AppLocale, storage: Pick<Storage, "setItem"> | null = typeof window === "undefined" ? null : window.localStorage): void {
  try {
    storage?.setItem(APP_LOCALE_STORAGE_KEY, locale);
  } catch {
    // Locale persistence is best-effort when webview storage is unavailable.
  }
}

export function translateText(locale: AppLocale, message: string): string {
  return locale === "pt-BR" && Object.prototype.hasOwnProperty.call(PT_BR_MESSAGES, message)
    ? PT_BR_MESSAGES[message as TranslationKey]
    : message;
}

let activeLocale: AppLocale = "en";

export function translate(message: string): string {
  return translateText(activeLocale, message);
}

export function setActiveLocale(locale: AppLocale): void {
  activeLocale = locale;
}

export function formatLocaleNumber(value: number, locale: AppLocale = activeLocale, options?: Intl.NumberFormatOptions): string {
  return new Intl.NumberFormat(locale, options).format(value);
}

export function formatLocalePercent(value: number, locale: AppLocale = activeLocale): string {
  return new Intl.NumberFormat(locale, { style: "percent", maximumFractionDigits: 1 }).format(value);
}

export function formatLocaleCurrency(
  value: number,
  locale: AppLocale = activeLocale,
  currency = "USD",
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(locale, { style: "currency", currency, ...options }).format(value);
}

export function formatLocaleDate(value: string | number | Date, locale: AppLocale = activeLocale): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(new Date(value));
}

export function formatLocaleDuration(valueMs: number, locale: AppLocale = activeLocale): string {
  if (!Number.isFinite(valueMs) || valueMs < 0) return translateText(locale, "Unavailable");
  if (valueMs < 1000) return `${formatLocaleNumber(Math.round(valueMs), locale)} ms`;
  const seconds = valueMs / 1000;
  return seconds < 60
    ? `${formatLocaleNumber(Number(seconds.toFixed(1)), locale)} s`
    : `${Math.floor(seconds / 60)}m ${formatLocaleNumber(Math.round(seconds % 60), locale)}s`;
}

type I18nContextValue = {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  t: (message: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>(() => loadAppLocale());
  setActiveLocale(locale);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: (next) => {
      const normalized = normalizeAppLocale(next);
      saveAppLocale(normalized);
      setLocaleState(normalized);
    },
    t: (message) => translateText(locale, message),
  }), [locale]);

  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider.");
  return context;
}
